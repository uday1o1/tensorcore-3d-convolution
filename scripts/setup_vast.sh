#!/usr/bin/env bash
# Provision a rented GPU instance for this project, and launch training on it.
#
# This is the one place provider-specific paths live. Everything else in the
# repository resolves paths from its own location and reads environment
# variables, so it runs unchanged on any machine.
#
#   scripts/setup_vast.sh launch setup          provision, detached, resumable
#   scripts/setup_vast.sh launch train <T> [<T> ...]  train in sequence, detached
#   scripts/setup_vast.sh status                 what has finished, what is running
#   source "$WORK/env.sh"                        environment for running anything
#
# Every stage writes a marker when it completes, so rerunning after a dropped
# connection resumes where it stopped. Logs and results go under $WORK, outside
# the repository checkout, so `git pull` on the instance never collides with
# freshly written files.
#
# Defaults suit the Vast.ai PyTorch image. Override any of them:
#   WORK=/workspace  VENV=/venv/main  MIN_FREE_GB=100
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="${WORK:-/workspace}"
VENV="${VENV:-/venv/main}"
MIN_FREE_GB="${MIN_FREE_GB:-100}"
LOGDIR="$WORK/logs"
MARK="$WORK/.setup"
MEDNEXT_DIR="$WORK/MedNeXt"
TASK_TAR_URL="https://msd-for-monai.s3-us-west-2.amazonaws.com/Task03_Liver.tar"
PLANS="nnUNetPlansv2.1_trgSp_1x1x1"
mkdir -p "$LOGDIR" "$MARK"

write_env() {
  cat > "$WORK/env.sh" << EOF
# Generated by scripts/setup_vast.sh
[ -f "$VENV/bin/activate" ] && source "$VENV/bin/activate"
export nnUNet_raw_data_base="$WORK/nnUNet_raw_data_base"
export nnUNet_preprocessed="$WORK/nnUNet_preprocessed"
export RESULTS_FOLDER="$WORK/RESULTS_FOLDER"
export BENCH_RESULTS_DIR="$WORK/bench_results"
export PYTHONPATH="$REPO/src\${PYTHONPATH:+:\$PYTHONPATH}"
EOF
  mkdir -p "$WORK/nnUNet_raw_data_base" "$WORK/nnUNet_preprocessed" \
           "$WORK/RESULTS_FOLDER" "$WORK/bench_results/validation"
}

say() { echo "$(date '+%F %T') $*"; }
# venv activate scripts reference unset variables, which set -u turns fatal.
load_env() { set +u; source "$WORK/env.sh"; set -u; }
done_stage() { [ -f "$MARK/$1.done" ]; }
finish_stage() { touch "$MARK/$1.done"; say "stage $1 complete"; }

free_gb() { df -BG --output=avail "$WORK" | tail -1 | tr -dc '0-9'; }
need_space() {
  local f; f=$(free_gb)
  if [ "$f" -lt "$1" ]; then
    say "ABORT: $f GB free on $WORK, stage needs $1 GB"; exit 1
  fi
}

# The archive host serves one connection at a few MB/s and a single stream
# was seen to stall outright, so fetch byte ranges in parallel. A part already
# at its full size is kept, so rerunning resumes.
download_parallel() {
  local url="$1" out="$2" n=16 size chunk i s e want part pids=()
  size=$(curl -sIL "$url" | tr -d '\r' | awk 'tolower($1)=="content-length:" {v=$2} END {print v}')
  [ -n "$size" ] || { say "could not read archive size"; return 1; }
  [ -f "$out" ] && [ "$(stat -c%s "$out")" = "$size" ] && return 0
  chunk=$(( (size + n - 1) / n ))
  for i in $(seq 0 $((n - 1))); do
    s=$((i * chunk)); e=$(( (i + 1) * chunk - 1 )); [ "$e" -ge "$size" ] && e=$((size - 1))
    part="$out.part$i"; want=$((e - s + 1))
    [ -f "$part" ] && [ "$(stat -c%s "$part")" = "$want" ] && continue
    ( for try in 1 2 3 4 5; do
        curl -sS -L --speed-limit 100000 --speed-time 60 -r "$s-$e" -o "$part" "$url" \
          && [ "$(stat -c%s "$part")" = "$want" ] && exit 0
        sleep 5
      done; exit 1 ) &
    pids+=($!)
  done
  for i in "${pids[@]}"; do wait "$i" || return 1; done
  for i in $(seq 0 $((n - 1))); do cat "$out.part$i"; done > "$out" && rm -f "$out".part*
  [ "$(stat -c%s "$out")" = "$size" ]
}

stage_preflight() {
  done_stage preflight && return
  say "preflight"
  nvidia-smi --query-gpu=name,driver_version,power.limit,power.default_limit,clocks.max.sm \
    --format=csv | tee "$LOGDIR/host.txt"
  grep -m1 "model name" /proc/cpuinfo | tee -a "$LOGDIR/host.txt"
  # The archive, its extraction, the converted copy and the preprocessed
  # output overlap during setup; intermediates are deleted as soon as the
  # next stage no longer needs them, but the peak still needs this much.
  need_space "$MIN_FREE_GB"
  finish_stage preflight
}

stage_deps() {
  done_stage deps && return
  say "dependencies"
  load_env
  [ -d "$MEDNEXT_DIR" ] || git clone -q https://github.com/MIC-DKFZ/MedNeXt.git "$MEDNEXT_DIR"
  # The fork still names the pre-rename package when it locates preprocessors,
  # so planning fails until this is corrected.
  sed -i 's/current_module="nnunet.preprocessing"/current_module="nnunet_mednext.preprocessing"/' \
    "$MEDNEXT_DIR/nnunet_mednext/experiment_planning/experiment_planner_baseline_3DUNet.py"
  # torch from the cu128 index at the version every committed result used.
  # cuDNN's version decides which algorithms it can select, so letting the
  # image's torch or default PyPI choose would change the measurement.
  pip install -q "torch==2.11.0" --index-url https://download.pytorch.org/whl/cu128 || exit 1
  pip install -q "numpy==2.5.3" surface-distance || exit 1
  pip install -q -e "$MEDNEXT_DIR" || exit 1
  python -c "import torch; print('torch', torch.__version__, 'cudnn', torch.backends.cudnn.version())" \
    | tee -a "$LOGDIR/host.txt"
  finish_stage deps
}

stage_trainers() {
  # Symlinked, not copied: the trainers locate their shared modules relative
  # to their own resolved path, which a copy would break.
  say "installing trainers"
  local dst="$MEDNEXT_DIR/nnunet_mednext/training/network_training/MedNeXt"
  for f in "$REPO"/src/trainers/*.py; do ln -sf "$f" "$dst/$(basename "$f")"; done
}

stage_data() {
  done_stage data && return
  load_env
  local raw="$WORK/download"
  mkdir -p "$raw"
  if ! done_stage download; then
    say "downloading MSD Task03 Liver"
    need_space 60
    download_parallel "$TASK_TAR_URL" "$raw/Task03_Liver.tar" || exit 1
    finish_stage download
  fi
  if ! done_stage extract; then
    say "extracting"
    tar -xf "$raw/Task03_Liver.tar" -C "$raw" || exit 1
    rm -f "$raw/Task03_Liver.tar"
    finish_stage extract
  fi
  if ! done_stage convert; then
    say "converting to nnU-Net v1 layout"
    mednextv1_convert_decathlon_task -i "$raw/Task03_Liver" || exit 1
    rm -rf "$raw"
    finish_stage convert
  fi
  say "planning and preprocessing"
  # -tf 3: the default of 8 full-resolution workers ran out of memory on the
  # largest volumes and stalled without erroring.
  mednextv1_plan_and_preprocess -t 3 -pl3d ExperimentPlanner3D_v21_customTargetSpacing_1x1x1 \
    -pl2d None -tf 3 -tl 3 || exit 1
  rm -rf "$nnUNet_raw_data_base/nnUNet_cropped_data"
  finish_stage data
}

stage_smoke() {
  load_env
  say "smoke test: correctness, then trainer discovery"
  python "$REPO/bench/verify_correctness.py" | tail -3 || exit 1
  python - << 'PY' || exit 1
import glob, os, sys
from nnunet_mednext.training.model_restore import recursive_find_python_class
import nnunet_mednext
base = [os.path.join(os.path.dirname(nnunet_mednext.__file__), "training", "network_training")]
names = [os.path.basename(f)[:-3] for f in glob.glob(os.path.join(os.environ["PYTHONPATH"].split(":")[0], "trainers", "nnUNetTrainer*.py"))]
bad = [n for n in names
       if recursive_find_python_class(base, n, "nnunet_mednext.training.network_training") is None]
print(f"{len(names) - len(bad)}/{len(names)} trainers discoverable")
sys.exit(1 if bad else 0)
PY
  say "smoke test passed"
}

cmd_setup() {
  write_env
  stage_preflight
  stage_deps
  stage_trainers
  stage_data
  stage_smoke
  say "SETUP COMPLETE"
}

cmd_train() {
  local trainer="$1"
  load_env
  stage_trainers
  local out="$RESULTS_FOLDER/nnUNet/3d_fullres/Task003_Liver/${trainer}__${PLANS}/fold_0"
  local src="$RESULTS_FOLDER/nnUNet/3d_fullres/Task003_Liver/nnUNetTrainerV2_MedNeXt_B_k3_150ep_s1__${PLANS}/fold_0/model_final_checkpoint.model"
  export MEDNEXT_UPKERN_SOURCE="${MEDNEXT_UPKERN_SOURCE:-$src}"
  say "training $trainer"
  mednextv1_train 3d_fullres "$trainer" Task003_Liver 0 --use_compressed_data -p "$PLANS"
  local rc=$?
  # The per-case validation summary is small and is the raw input to every
  # accuracy claim. Copy it out of the run directory immediately: when an
  # earlier instance was destroyed, only derived numbers survived.
  if [ -f "$out/validation_raw/summary.json" ]; then
    cp "$out/validation_raw/summary.json" "$BENCH_RESULTS_DIR/validation/${trainer}_summary.json"
    say "TRAINED $trainer, summary saved"
  else
    say "FAILED $trainer (exit $rc), no validation summary"
  fi
  return $rc
}

cmd_status() {
  ls "$MARK" 2>/dev/null | sed 's/^/  done: /'
  pgrep -af "mednextv1_train|setup_vast.sh" | grep -v pgrep | sed 's/^/  running: /'
  ls "$WORK/bench_results/validation" 2>/dev/null | sed 's/^/  summary: /'
  df -h "$WORK" | tail -1 | sed 's/^/  disk: /'
}

case "${1:-}" in
  launch)
    # Detach fully: survives the ssh session ending and the connection dropping.
    shift
    log="$LOGDIR/$1${2:+_$2}.log"
    setsid nohup "$REPO/scripts/setup_vast.sh" "$@" > "$log" 2>&1 < /dev/null & disown
    echo "launched: $* (log $log)"
    ;;
  setup) cmd_setup ;;
  train)
    # A failed run is reported and the sequence moves on, so one bad
    # configuration does not idle the GPU for the rest of the queue.
    [ -n "${2:-}" ] || { echo "usage: $0 train <Trainer> [<Trainer> ...]"; exit 2; }
    shift; for t in "$@"; do cmd_train "$t"; done; say "QUEUE DONE" ;;
  status) cmd_status ;;
  *) sed -n '2,20p' "$0"; exit 2 ;;
esac
